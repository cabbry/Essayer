/// La traduction anglaise des défis, dans le même ordre que les listes
/// françaises de `Challenges`. Le texte français reste l'identifiant du défi
/// (CloudKit, historique, défis retirés) ; on ne traduit qu'à l'affichage.
extension Challenges {
    static func localized(_ french: String) -> String {
        guard !Lang.isFrench else { return french }
        return englishByFrench[french] ?? french
    }

    private static let englishByFrench: [String: String] = {
        var map: [String: String] = [:]
        for (french, english) in zip(general, englishGeneral) { map[french] = english }
        for (french, english) in zip(replacements, englishReplacements) { map[french] = english }
        for season in Season.allCases {
            for (french, english) in zip(seasonal(season), englishSeasonal(season)) { map[french] = english }
        }
        return map
    }()

    static func englishSeasonal(_ season: Season) -> [String] {
        switch season {
        case .spring: englishSpring
        case .summer: englishSummer
        case .autumn: englishAutumn
        case .winter: englishWinter
        }
    }

